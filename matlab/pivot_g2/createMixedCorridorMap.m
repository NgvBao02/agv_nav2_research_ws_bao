function map = createMixedCorridorMap(resolution)
%CREATEMIXEDCORRIDORMAP Ban do ket hop loi hep, chu L, chu S va vung mo.
map = initializeWarehouseMap('MIXED_CORRIDOR', 18, 12, resolution, ...
    'Moi truong hon hop gom duong chu S, goc lien tiep va vung mo.');
o = map.occupancy;
rectangles = [2.0 1.0 0.6 5.0; 2.0 7.4 0.6 3.6; ...
              4.4 2.8 0.6 8.2; 6.8 1.0 0.6 6.2; ...
              9.2 4.5 0.6 6.5; 11.6 1.0 0.6 6.0; ...
              14.0 3.0 0.6 8.0; 15.9 1.0 0.5 4.0; ...
              7.4 8.8 1.8 0.6];
for i = 1:size(rectangles,1)
    o = addRectangleObstacle(o, resolution, rectangles(i,:));
end
map.occupancy = o;
map.startGoalPairs = [ ...
    createScenario('MIXED_FULL_ROUTE', [0.7 0.7], [17.3 11.3]), ...
    createScenario('S_SHAPED_ROUTE', [3.5 1.1], [10.5 10.9]), ...
    createScenario('NARROW_TO_OPEN', [5.9 1.1], [17.3 8.1]), ...
    createScenario('CONSECUTIVE_CORNERS', [0.7 6.7], [13.1 1.1]), ...
    createScenario('MULTI_ROUTE_MIX', [17.3 1.1], [0.7 10.9])];
end
