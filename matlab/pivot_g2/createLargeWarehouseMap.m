function map = createLargeWarehouseMap(resolution)
%CREATELARGEWAREHOUSEMAP Ban do 20 x 20 m voi 10 day ke.
map = initializeWarehouseMap('LARGE_WAREHOUSE', 20, 20, resolution, ...
    'Kho lon co 10 day ke, hanh lang chinh va nhieu tuyen thay the.');
o = map.occupancy;
xPositions = 1.8:1.8:18.0;
ySegments = [1.0 2.8; 5.0 3.0; 10.0 3.0; 15.0 3.8];
for x = xPositions
    for j = 1:size(ySegments,1)
        o = addRectangleObstacle(o, resolution, ...
            [x ySegments(j,1) 0.55 ySegments(j,2)]);
    end
end
map.occupancy = o;
map.startGoalPairs = [ ...
    createScenario('FULL_SCALE_DIAGONAL', [0.7 0.7], [19.3 19.3]), ...
    createScenario('MAIN_CORRIDOR', [0.7 4.4], [19.3 4.4]), ...
    createScenario('LONG_RACK_AISLE', [2.9 0.7], [2.9 19.3]), ...
    createScenario('MULTI_CROSS_AISLE', [6.5 0.7], [15.5 19.3]), ...
    createScenario('ALTERNATIVE_ROUTES', [19.3 1.1], [0.7 16.1])];
end
