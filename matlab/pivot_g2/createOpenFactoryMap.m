function map = createOpenFactoryMap(resolution)
%CREATEOPENFACTORYMAP Ban do 20 x 15 m voi may moc phan bo thua.
map = initializeWarehouseMap('OPEN_FACTORY', 20, 15, resolution, ...
    'Nha may mo voi cac cum may hinh chu nhat phan bo thua.');
o = map.occupancy;
rectangles = [3.0 2.0 1.8 1.4; 7.0 5.0 2.0 1.4; ...
              12.0 2.0 2.4 1.6; 15.5 7.0 1.8 2.2; ...
              3.5 10.0 2.2 1.5; 10.5 10.5 2.2 1.5];
for i = 1:size(rectangles,1)
    o = addRectangleObstacle(o, resolution, rectangles(i,:));
end
map.occupancy = o;
map.startGoalPairs = [ ...
    createScenario('OPEN_DIAGONAL', [0.7 0.7], [19.3 14.3]), ...
    createScenario('SOUTH_ROUTE', [0.7 4.3], [19.3 4.3]), ...
    createScenario('NORTH_ROUTE', [1.1 13.7], [18.9 10.1]), ...
    createScenario('SPARSE_MACHINES', [6.1 1.1], [14.9 13.9]), ...
    createScenario('MULTIPLE_OPEN_ROUTES', [18.9 1.1], [1.1 9.1])];
end
